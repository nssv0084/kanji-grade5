/** 小学校で習う読みだけにした音訓 */
export function schoolReadings(kanji: string): Pick<KanjiEntry, "on" | "kun"> {
  const e = GRADE5[kanji];
  const later = new Set(LATER_READINGS[kanji] ?? []);
  return { on: e.on.filter((r) => !later.has(r)), kun: e.kun.filter((r) => !later.has(r)) };
}
